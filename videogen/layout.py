# --- sizing / placement ----------------------------------------------------
def _safe_dim(mobj, attr):
    try:
        return getattr(mobj, attr)
    except Exception:
        return 0.0


def is_empty(mobj):
    """True for a mobject with nothing to draw; geometry calls raise on these."""
    if mobj is None:
        return True
    if len(mobj.submobjects):
        return False
    return len(getattr(mobj, "points", [])) == 0


def fit(mobj, w=CONTENT_W, h=CONTENT_H):
    """Scale down (never up) until the mobject fits the given box."""
    if is_empty(mobj):
        return mobj
    width = _safe_dim(mobj, "width")
    height = _safe_dim(mobj, "height")
    if width > w > 0:
        mobj.scale_to_fit_width(w)
        height = _safe_dim(mobj, "height")
    if height > h > 0:
        mobj.scale_to_fit_height(h)
    return mobj


def place(mobj, w=CONTENT_W, h=CONTENT_H, center=None):
    """Fit into the content band and centre it there."""
    if is_empty(mobj):
        return mobj
    fit(mobj, w, h)
    mobj.move_to(CONTENT_CENTER if center is None else center)
    return mobj


def place_top(mobj, w=CONTENT_W, h=CONTENT_H):
    """Fit, then hang the mobject from the top of the content band.

    Centring short content leaves an ugly gap under the heading, so list-like
    sections grow downward from a fixed top edge instead.
    """
    if is_empty(mobj):
        return mobj
    fit(mobj, w, h)
    mobj.set_x(0)
    mobj.align_to(np.array([0.0, CONTENT_TOP, 0.0]), UP)
    return mobj


def split(left, right, ratio=0.44, gap=0.55):
    """Two columns that cannot overlap: each is clipped to its own half."""
    lw = (CONTENT_W - gap) * ratio
    rw = (CONTENT_W - gap) * (1.0 - ratio)
    if not is_empty(left):
        fit(left, lw, CONTENT_H)
        left.move_to(CONTENT_CENTER + LEFT * ((CONTENT_W - lw) / 2.0))
    if not is_empty(right):
        fit(right, rw, CONTENT_H)
        right.move_to(CONTENT_CENTER + RIGHT * ((CONTENT_W - rw) / 2.0))
    return VGroup(left, right)


# --- text ------------------------------------------------------------------
def para(text, width=WRAP_FULL, size=SIZE_BODY, color=FG, font=FONT, weight=None):
    """Word-wrapped Text. Manim's Text does not wrap on its own."""
    clean = " ".join(str(text or "").split()) or " "
    wrapped = "\n".join(textwrap.wrap(clean, width)) or " "
    kwargs = dict(font=font, font_size=size, color=color, line_spacing=0.85)
    if weight:
        kwargs["weight"] = weight
    return Text(wrapped, **kwargs)


_KEYWORD_WORDS = (
    "def class return if elif else while for in not and or is None True False "
    "import from as with try except finally raise lambda yield pass break "
    "continue global assert del await async"
).split()

# Non-capturing on purpose: this pattern is embedded inside the named groups of
# _MARKUP_TOKENS below, and a nested capturing group would break `lastgroup`.
_KEYWORDS = r"\b(?:" + "|".join(_KEYWORD_WORDS) + r")\b"


def _highlight(body):
    """Map exact character spans to colours for Manim's t2c."""
    spans = {}
    for m in re.finditer(r"\b\d+\b", body):
        spans[f"[{m.start()}:{m.end()}]"] = CODE_NUM
    for m in re.finditer(_KEYWORDS, body):
        spans[f"[{m.start()}:{m.end()}]"] = CODE_KW
    for m in re.finditer(r"def\s+(\w+)", body):
        spans[f"[{m.start(1)}:{m.end(1)}]"] = CODE_FN
    for m in re.finditer(r"(\"[^\"]*\"|'[^']*')", body):
        spans[f"[{m.start()}:{m.end()}]"] = CODE_STR
    m = re.search(r"#.*$", body)
    if m:  # applied last so it wins over anything inside the comment
        spans[f"[{m.start()}:{m.end()}]"] = CODE_COM
    return spans


def code_block(lines, size=SIZE_CODE):
    """A syntax-highlighted code listing that keeps its indentation.

    Manim aligns mobjects by their visible bounding box, so leading spaces are
    silently dropped by `arrange(aligned_edge=LEFT)`. We therefore strip the
    indent, align every line flush left, then shift each one right by an exact
    multiple of the monospace character width.
    """
    ruler = Text("M" * 10, font=MONO, font_size=size)
    char_w = _safe_dim(ruler, "width") / 10.0

    group = VGroup()
    offsets = []
    for raw in lines:
        body = str(raw or "").rstrip()
        stripped = body.lstrip(" ")
        offsets.append((len(body) - len(stripped)) * char_w)
        group.add(
            Text(
                stripped or " ",
                font=MONO,
                font_size=size,
                color=FG,
                t2c=_highlight(stripped),
            )
        )

    if not len(group):
        return group
    group.arrange(DOWN, buff=0.17, aligned_edge=LEFT)
    for line, dx in zip(group, offsets):
        line.shift(RIGHT * dx)
    return group


def header(text):
    """Section heading pinned to the title band, with an accent rule."""
    title = para(text, width=WRAP_HEAD, size=SIZE_HEAD, color=FG, weight=BOLD)
    fit(title, CONTENT_W, 1.05)
    title.move_to(UP * TITLE_Y)
    half = max(_safe_dim(title, "width") / 2.0, 0.4) + 0.18
    rule = Line(LEFT * half, RIGHT * half, stroke_width=3, color=ACCENT)
    rule.next_to(title, DOWN, buff=0.2)
    return VGroup(title, rule)


def panel(inner, pad_x=0.5, pad_y=0.42):
    """A rounded card sitting behind `inner`."""
    w = max(_safe_dim(inner, "width") + 2 * pad_x, 1.0)
    h = max(_safe_dim(inner, "height") + 2 * pad_y, 1.0)
    card = RoundedRectangle(
        corner_radius=0.18,
        width=w,
        height=h,
        fill_color=PANEL_FILL,
        fill_opacity=1.0,
        stroke_color=PANEL_STROKE,
        stroke_width=2,
    )
    card.move_to(inner.get_center())
    return VGroup(card, inner)


def bullet_rows(points, width=WRAP_FULL, size=SIZE_BODY, buff=0.34):
    """Dot + wrapped text rows, left-aligned in a column."""
    rows = VGroup()
    for i, text in enumerate(points):
        dot = Dot(radius=0.075, color=SERIES[i % len(SERIES)])
        body = para(text, width=width, size=size)
        dot.move_to(body.get_corner(UP + LEFT) + LEFT * 0.3 + DOWN * 0.22)
        rows.add(VGroup(dot, body))
    if len(rows) == 0:
        return rows
    # Re-arrange as a proper column, keeping each dot glued to its text.
    rows.arrange(DOWN, buff=buff, aligned_edge=LEFT)
    return rows


# --- diagram primitives ----------------------------------------------------
def nodes(labels, size=SIZE_SMALL, uniform=True, min_w=1.9, height=0.95):
    """A VGroup of labelled rounded boxes, all the same size by default."""
    boxes = VGroup()
    labs = []
    for text in labels:
        labs.append(Text(str(text), font=FONT, font_size=size, color=FG))
    widest = max([_safe_dim(l, "width") for l in labs] + [0.0])
    for i, lab in enumerate(labs):
        color = SERIES[i % len(SERIES)]
        w = max(min_w, (widest if uniform else _safe_dim(lab, "width")) + 0.62)
        box = RoundedRectangle(
            corner_radius=0.14,
            width=w,
            height=height,
            fill_color=NODE_FILL,
            fill_opacity=1.0,
            stroke_color=color,
            stroke_width=3,
        )
        lab.move_to(box.get_center())
        boxes.add(VGroup(box, lab))
    return boxes


def _connect(a, b, color=MUTED):
    """Arrow between two node boundaries.

    Trimming a centre-to-centre arrow with `buff` puts both ends inside the
    opaque boxes, which hides the tip. Anchor to the boundary points instead.
    """
    delta = b.get_center() - a.get_center()
    norm = np.linalg.norm(delta)
    if norm == 0:
        return VGroup()
    unit = delta / norm
    return Arrow(
        a.get_boundary_point(unit), b.get_boundary_point(-unit), buff=0.09,
        stroke_width=3, color=color, max_tip_length_to_length_ratio=0.32,
    )


def diagram(shape, labels):
    """Build one of the supported parametric diagrams.

    Returns (group, node_list) so callers can highlight individual nodes.
    """
    labels = [str(x) for x in labels if str(x).strip()]
    if not labels:
        labels = ["..."]
    shape = (shape or "row").lower()

    if shape == "stack":
        ns = nodes(labels)
        ns.arrange(DOWN, buff=0.22)
        return VGroup(ns), list(ns)

    if shape == "flow":
        ns = nodes(labels)
        ns.arrange(RIGHT, buff=1.05)
        arrows = VGroup(*[_connect(ns[i], ns[i + 1]) for i in range(len(ns) - 1)])
        return VGroup(arrows, ns), list(ns)

    if shape == "tree":
        ns = nodes(labels, min_w=1.5, height=0.85)
        edges = VGroup()
        for i, node in enumerate(ns):
            level = int(math.floor(math.log2(i + 1)))
            in_level = i - (2 ** level - 1)
            count = 2 ** level
            x = ((in_level + 0.5) / count - 0.5) * 9.6
            y = 1.9 - level * 1.75
            node.move_to(np.array([x, y, 0.0]))
        for i in range(1, len(ns)):
            edges.add(
                Line(
                    ns[(i - 1) // 2].get_bottom(), ns[i].get_top(),
                    stroke_width=3, color=PANEL_STROKE,
                )
            )
        return VGroup(edges, ns), list(ns)

    if shape == "grid":
        ns = nodes(labels, min_w=1.5, height=0.9)
        cols = max(1, int(math.ceil(math.sqrt(len(ns)))))
        ns.arrange_in_grid(cols=cols, buff=0.3)
        return VGroup(ns), list(ns)

    ns = nodes(labels)  # "row"
    ns.arrange(RIGHT, buff=0.35)
    return VGroup(ns), list(ns)


def column(title, points, width_chars, accent):
    """A titled bullet column used by the comparison layout."""
    head = para(title, width=22, size=SIZE_BODY, color=accent, weight=BOLD)
    body = VGroup()
    for text in points:
        body.add(para("•  " + str(text), width=width_chars, size=SIZE_SMALL))
    if not len(body):
        return VGroup(head)  # arrange() would raise on an empty child group
    body.arrange(DOWN, buff=0.26, aligned_edge=LEFT)
    return VGroup(head, body).arrange(DOWN, buff=0.4, aligned_edge=LEFT)


# --- execution primitives --------------------------------------------------
# Everything below exists so that a lesson can *animate what code does* rather
# than display it: a line lighting up, a variable changing, a pointer walking an
# array, a recursion stack growing and unwinding. Like the rest of this module
# they return pre-fitted mobjects, so generated scenes compose them instead of
# positioning things by hand.

_MARKUP_TOKENS = re.compile(
    r"(?P<com>\#.*$)"
    r"|(?P<str>\"[^\"]*\"|'[^']*')"
    + r"|(?P<kw>" + _KEYWORDS + r")"
    + r"|(?P<num>\b\d+(?:\.\d+)?\b)"
    + r"|(?P<fn>\b[A-Za-z_]\w*(?=\())"
)

_MARKUP_COLORS = {
    "com": CODE_COM,
    "str": CODE_STR,
    "kw": CODE_KW,
    "num": CODE_NUM,
    "fn": CODE_FN,
}


def _escape(text):
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def _markup(body):
    """Colour one line of Python as Pango markup."""
    out = []
    pos = 0
    for match in _MARKUP_TOKENS.finditer(body):
        out.append(_escape(body[pos:match.start()]))
        color = _MARKUP_COLORS.get(match.lastgroup, FG)
        out.append(f'<span foreground="{color}">{_escape(match.group(0))}</span>')
        pos = match.end()
    out.append(_escape(body[pos:]))
    return "".join(out) or " "


def markup_code_block(lines, size=SIZE_CODE):
    """A syntax-highlighted listing built from MarkupText, one mobject per line.

    Preferred over Manim's `Code` mobject, which brings its own frame, font and
    background and so cannot be styled into this theme. Indentation is restored
    the same way `code_block` does it: Manim aligns by visible bounding box, so
    leading spaces would be silently dropped by `arrange(aligned_edge=LEFT)`.
    Each line is therefore stripped, aligned flush left, then shifted right by
    an exact multiple of the monospace character width.

    Index the result to address a line: `code[3]` is the fourth line.
    """
    ruler = Text("M" * 10, font=MONO, font_size=size)
    char_w = _safe_dim(ruler, "width") / 10.0

    group = VGroup()
    offsets = []
    for raw in lines:
        body = str(raw or "").rstrip()
        stripped = body.lstrip(" ")
        offsets.append((len(body) - len(stripped)) * char_w)
        group.add(MarkupText(_markup(stripped), font=MONO, font_size=size, color=FG))

    if not len(group):
        return group
    group.arrange(DOWN, buff=0.17, aligned_edge=LEFT)
    for line, dx in zip(group, offsets):
        line.shift(RIGHT * dx)
    return group


class VarTable(VGroup):
    """A live variable panel: name on the left, current value on the right.

        state = VarTable(["i", "total"])
        split(code, state)
        self.play(state.set_value("i", 3))

    `set_value` returns an animation, so a variable changing is something the
    viewer watches happen rather than a value that silently differs.
    """

    def __init__(self, names, size=SIZE_SMALL, gap=0.5):
        super().__init__()
        self._size = size
        self._values = {}

        labels = [Text(f"{n}", font=MONO, font_size=size, color=MUTED) for n in names]
        widest = max([_safe_dim(l, "width") for l in labels] + [0.4])

        rows = VGroup()
        for name, label in zip(names, labels):
            value = Text("—", font=MONO, font_size=size, color=ACCENT_3)
            label.move_to(ORIGIN, aligned_edge=LEFT)
            value.move_to(RIGHT * (widest + gap), aligned_edge=LEFT)
            self._values[str(name)] = value
            rows.add(VGroup(label, value))

        if len(rows):
            rows.arrange(DOWN, buff=0.22, aligned_edge=LEFT)
        self.add(rows)

    def set_value(self, name, text):
        """Animation that swaps one variable's displayed value."""
        old = self._values[str(name)]
        new = Text(str(text), font=MONO, font_size=self._size, color=ACCENT_3)
        new.move_to(old.get_left(), aligned_edge=LEFT)
        return Transform(old, new)

    def value_mob(self, name):
        """The value mobject, for Indicate / Flash / Circumscribe."""
        return self._values[str(name)]


class ArrayRow(VGroup):
    """A row of indexed cells — an array, a buffer, or a queue.

        arr = ArrayRow([5, 2, 9, 1])
        self.play(arr.set_value(2, 7))
        self.play(Indicate(arr.cell(0)))

    `cells` is a plain list, so a pointer can walk it and SurroundingRectangle
    can frame any single element.
    """

    def __init__(self, values, size=SIZE_SMALL, cell_w=1.05, cell_h=0.85,
                 show_index=True):
        super().__init__()
        self._size = size
        self.cells = []
        self._texts = []

        boxes = VGroup()
        for value in values:
            box = Rectangle(
                width=cell_w, height=cell_h,
                fill_color=NODE_FILL, fill_opacity=1.0,
                stroke_color=PANEL_STROKE, stroke_width=2,
            )
            text = Text(str(value), font=MONO, font_size=size, color=FG)
            text.move_to(box.get_center())
            cell = VGroup(box, text)
            self.cells.append(cell)
            self._texts.append(text)
            boxes.add(cell)

        if len(boxes):
            boxes.arrange(RIGHT, buff=0.08)
        self.add(boxes)

        if show_index and len(boxes):
            marks = VGroup()
            for i, cell in enumerate(self.cells):
                mark = Text(str(i), font=MONO, font_size=size * 0.72, color=MUTED)
                mark.next_to(cell, DOWN, buff=0.12)
                marks.add(mark)
            self.add(marks)

    def cell(self, index):
        return self.cells[index]

    def set_value(self, index, value):
        """Animation that rewrites one cell in place."""
        old = self._texts[index]
        new = Text(str(value), font=MONO, font_size=self._size, color=ACCENT_4)
        new.move_to(old.get_center())
        return Transform(old, new)


class Pointer(VGroup):
    """A labelled arrow that walks along cells or nodes.

        i = Pointer("i")
        i.next_to(arr.cell(0), DOWN, buff=0.5)
        self.play(i.point_to(arr.cell(1)))
    """

    def __init__(self, label, color=ACCENT_3, size=SIZE_SMALL):
        super().__init__()
        arrow = Arrow(
            start=DOWN * 0.6, end=ORIGIN, buff=0.0, color=color,
            stroke_width=4, max_tip_length_to_length_ratio=0.4,
        )
        text = Text(str(label), font=MONO, font_size=size, color=color)
        text.next_to(arrow, DOWN, buff=0.08)
        self.add(arrow, text)

    def point_to(self, target, buff=0.5):
        """Animation that slides this pointer under `target`."""
        return self.animate.next_to(target, DOWN, buff=buff)


class StackFrames(VGroup):
    """A call stack that grows upward from a fixed base.

        stack = StackFrames(max_frames=5)
        place(stack)
        self.play(FadeIn(stack.push("fib(3)")))
        self.play(FadeOut(stack.pop()))

    `push` and `pop` return the frame mobject rather than an animation, so the
    scene chooses how it enters and leaves. Space for `max_frames` is reserved
    up front by an invisible spacer, so `place()` sizes the whole stack once and
    later pushes cannot grow it out of the content band.
    """

    def __init__(self, max_frames=5, width=3.4, height=0.62, buff=0.12,
                 size=SIZE_SMALL):
        super().__init__()
        self._frames = []
        self._w = width
        self._h = height
        self._buff = buff
        self._size = size
        self._max = max_frames

        spacer = Rectangle(
            width=width,
            height=max_frames * (height + buff),
            stroke_opacity=0.0, fill_opacity=0.0,
        )
        self.add(spacer)
        self._spacer = spacer

    def _slot(self, index):
        bottom = self._spacer.get_bottom()[1] + self._h / 2.0
        return np.array([
            self._spacer.get_center()[0],
            bottom + index * (self._h + self._buff),
            0.0,
        ])

    def push(self, label):
        """Build the next frame, positioned but not yet added to the scene."""
        index = min(len(self._frames), self._max - 1)
        color = SERIES[index % len(SERIES)]
        box = RoundedRectangle(
            corner_radius=0.1, width=self._w, height=self._h,
            fill_color=NODE_FILL, fill_opacity=1.0,
            stroke_color=color, stroke_width=3,
        )
        text = Text(str(label), font=MONO, font_size=self._size, color=FG)
        fit(text, self._w - 0.35, self._h - 0.18)
        frame = VGroup(box, text)
        frame.move_to(self._slot(index))
        text.move_to(box.get_center())
        self._frames.append(frame)
        return frame

    def pop(self):
        """The topmost frame, removed from the stack's bookkeeping."""
        return self._frames.pop() if self._frames else VGroup()

    def top(self):
        return self._frames[-1] if self._frames else None
